/**
 * Detects the most relevant industry domain from a natural language prompt across 16 sectors.
 */
export function detectDomainFromPrompt(prompt = "") {
  const p = prompt.toLowerCase();

  // 1. Events & Communities (Conferences, Summits, Festivals)
  if (p.includes("event") || p.includes("conference") || p.includes("summit") || p.includes("community") || p.includes("meetup") || p.includes("festival") || p.includes("hackathon") || p.includes("keynote")) {
    return "events_community";
  }

  // 2. Education & Learning (Courses, Bootcamps, Academies)
  if (p.includes("course") || p.includes("education") || p.includes("learn") || p.includes("academy") || p.includes("school") || p.includes("bootcamp") || p.includes("student") || p.includes("tutor") || p.includes("curriculum") || p.includes("masterclass")) {
    return "education";
  }

  // 3. Career, Resume & ATS Recruiting
  if (p.includes("resume") || p.includes("cv ") || p.includes(" cv") || p.includes("ats ") || p.includes(" ats") || p.includes("recruitment") || p.includes("hiring") || p.includes("talent acquisition")) {
    return "career_resume";
  }

  // 4. Developer Tools, Code & Infrastructure
  if (p.includes("ide") || p.includes("terminal") || p.includes("github") || p.includes("git ") || p.includes("devops") || p.includes("docker") || p.includes("kubernetes")) {
    return "developer_tools";
  }

  // 5. Fitness, Gym & Athletic Performance
  if (p.includes("fitness") || p.includes("gym") || p.includes("workout") || p.includes("crossfit") || p.includes("athletic") || p.includes("bodybuilding") || p.includes("personal trainer") || p.includes("weights") || p.includes("exercise")) {
    return "fitness_wellness";
  }

  // 6. Healthcare, Wellness & Skincare
  if (p.includes("skin") || p.includes("beauty") || p.includes("cosmetic") || p.includes("serum") || p.includes("botanical") || p.includes("health") || p.includes("clinic") || p.includes("wellness") || p.includes("doctor") || p.includes("medical") || p.includes("therapy") || p.includes("dermatol")) {
    return "healthcare_wellness";
  }

  // 7. Restaurants & Hospitality
  if (p.includes("restaurant") || p.includes("dining") || p.includes("italian") || p.includes("food") || p.includes("chef") || p.includes("menu") || p.includes("pasta") || p.includes("wine") || p.includes("bistro") || p.includes("tasting") || p.includes("cafe") || p.includes("hospitality") || p.includes("hotel") || p.includes("resort")) {
    return "restaurants_hospitality";
  }

  // 8. Real Estate
  if (p.includes("estate") || p.includes("home") || (p.includes("property") && !p.includes("intellectual property")) || p.includes("villa") || p.includes("penthouse") || p.includes("delhi") || p.includes("realtor") || p.includes("mansion") || p.includes("residence") || p.includes("apartments")) {
    return "real_estate";
  }

  // 9. Finance & Fintech
  if (p.includes("finance") || p.includes("fintech") || p.includes("banking") || p.includes("invest") || p.includes("wealth") || p.includes("trading") || p.includes("crypto") || p.includes("capital") || p.includes("equity") || p.includes("fund")) {
    return "fintech_finance";
  }

  // 10. E-Commerce & Consumer Brands
  if (p.includes("shop") || p.includes("store") || p.includes("ecommerce") || p.includes("e-commerce") || p.includes("brand") || p.includes("fashion") || p.includes("apparel") || p.includes("clothing") || p.includes("retail") || p.includes("sneaker")) {
    return "ecommerce";
  }

  // 11. AI Products & Generative Platforms
  if (p.includes("ai ") || p.includes("artificial intelligence") || p.includes("copilot") || p.includes("generative") || p.includes("cyber") || p.includes("threat") || p.includes("machine learning") || p.includes("neural") || p.includes("autonomous") || p.includes("llm") || p.includes("agent") || p.includes("prompt")) {
    return "ai_startup";
  }

  // 12. Portfolio & Creative Agencies
  if (p.includes("photo") || p.includes("architect") || p.includes("portfolio") || p.includes("designer") || p.includes("creative agency") || p.includes("studio") || p.includes("monograph") || p.includes("artist") || p.includes("exhibition")) {
    return "portfolio_agency";
  }

  // 13. B2B Solutions
  if (p.includes("enterprise") || p.includes("corporate") || p.includes("b2b") || p.includes("compliance") || p.includes("supply chain") || p.includes("procurement") || p.includes("industrial")) {
    return "b2b";
  }

  // 14. Service Business
  if (p.includes("service") || p.includes("consult") || p.includes("advisor") || p.includes("agency") || p.includes("contractor") || p.includes("law") || p.includes("accounting") || p.includes("legal") || p.includes("intellectual property")) {
    return "service_business";
  }

  // 15. SaaS & Cloud Apps (Default software catch-all)
  if (p.includes("saas") || p.includes("dashboard") || p.includes("subscription software") || p.includes("cloud tool") || p.includes("b2b platform") || p.includes("workflow app") || p.includes("crm")) {
    return "saas";
  }

  return "saas";
}

/**
 * Returns a curated image URL for a given domain and slot.
 */
export function getDomainImage(domain, slot = "hero", index = 0) {
  const collection = DOMAIN_IMAGE_COLLECTIONS[domain] || DOMAIN_IMAGE_COLLECTIONS.saas;
  const list = collection[slot] || collection.items || collection.hero;
  return list[index % list.length];
}

function safeStringUrl(val) {
  if (typeof val === "string") return val;
  if (typeof val === "object" && val !== null) return val.url || val.src || "";
  return "";
}

/**
 * Checks if a given image URL is empty, generic placeholder, or invalid.
 */
function isDummyOrInvalidUrl(url) {
  if (!url || typeof url !== "string") return true;
  const clean = url.trim().toLowerCase();
  return (
    clean === "" ||
    clean.includes("placeholder") ||
    clean.includes("dummy") ||
    clean.includes("example.com") ||
    clean.includes("via.placeholder") ||
    clean.includes("placehold.co") ||
    clean.includes("photo-1593508512255") || // Generic VR default
    clean.includes("photo-1600585154340") || // Generic monolith architecture block
    clean.includes("photo-1513694203232") ||
    clean.includes("photo-1492691527719")
  );
}

function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return hash;
}

/**
 * Resolves images in a page configuration to ensure they match the domain
 * and use valid, high-resolution photography rather than generic tech defaults.
 * Employs hash-based distribution to prevent identical image assignments across distinct projects.
 */
export function enrichPageConfigWithDomainImages(config, prompt = "") {
  if (!config || !Array.isArray(config.sections)) {
    return config;
  }
  const domain = detectDomainFromPrompt(prompt || config.metadata?.title || "");
  const collection = DOMAIN_IMAGE_COLLECTIONS[domain] || DOMAIN_IMAGE_COLLECTIONS.saas;
  const promptSeed = Math.abs(hashString(prompt + (config.metadata?.title || "")));

  let itemImgIdx = promptSeed % (collection.items.length || 1);
  let avatarIdx = promptSeed % (TESTIMONIAL_AVATARS.length || 1);

  const enrichedSections = config.sections.map((section) => {
    // 1. Hero media
    if (section.type === "hero" && section.content) {
      const currentUrl = safeStringUrl(section.content.media?.url || section.content.media);
      if (isDummyOrInvalidUrl(currentUrl)) {
        const heroVariantIdx = promptSeed % collection.hero.length;
        const selectedHero = collection.hero[heroVariantIdx] || collection.hero[0];
        return {
          ...section,
          content: {
            ...section.content,
            media: {
              ...section.content.media,
              type: "image",
              url: selectedHero,
              alt: `${config.metadata?.title || "Brand"} Hero Showcase`,
            },
          },
        };
      }
    }

    // 2. Showcase items
    if (section.type === "showcase" && section.content?.items) {
      const updatedItems = section.content.items.map((item, idx) => {
        const itemUrl = safeStringUrl(item.image);
        if (isDummyOrInvalidUrl(itemUrl)) {
          const replacement = collection.items[(itemImgIdx + idx) % collection.items.length];
          return { ...item, image: replacement };
        }
        return { ...item, image: itemUrl };
      });
      itemImgIdx += section.content.items.length;
      return {
        ...section,
        content: {
          ...section.content,
          items: updatedItems,
        },
      };
    }

    // 3. Gallery images
    if (section.type === "gallery" && section.content?.images) {
      const updatedImages = section.content.images.map((img, idx) => {
        const imgUrl = safeStringUrl(img.url || img);
        const replacement = collection.items[idx % collection.items.length];
        return {
          ...img,
          url: isDummyOrInvalidUrl(imgUrl) ? replacement : imgUrl,
        };
      });
      return {
        ...section,
        content: {
          ...section.content,
          images: updatedImages,
        },
      };
    }

    // 4. Video showcase poster
    if (section.type === "video_showcase" && section.content) {
      const posterUrl = safeStringUrl(section.content.posterUrl);
      if (isDummyOrInvalidUrl(posterUrl)) {
        return {
          ...section,
          content: {
            ...section.content,
            posterUrl: collection.ambiance?.[0] || collection.hero[0],
          },
        };
      }
    }

    // 5. Testimonial avatars (guarantee realistic verified portraits)
    if (section.type === "testimonials" && section.content?.items) {
      const updatedTestimonials = section.content.items.map((item) => {
        const avatarUrl = safeStringUrl(item.avatar);
        if (isDummyOrInvalidUrl(avatarUrl)) {
          const replacementAvatar = TESTIMONIAL_AVATARS[avatarIdx % TESTIMONIAL_AVATARS.length];
          avatarIdx++;
          return { ...item, avatar: replacementAvatar };
        }
        return item;
      });
      return {
        ...section,
        content: {
          ...section.content,
          items: updatedTestimonials,
        },
      };
    }

    return section;
  });

  return {
    ...config,
    sections: enrichedSections,
  };
}
